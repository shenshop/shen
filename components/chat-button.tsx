export function ChatButton({ links }: { links: { label: string; href: string }[] }) {
  const items = links.filter((l) => ICONS[l.label]);
  if (!items.length) return null;
  return (
    <div className="chat-fab">
      <span className="chat-hint">Напишіть нам</span>
      {items.map((l) => (
        <a
          key={l.label}
          href={l.href}
          target="_blank"
          rel="noopener"
          className="chat-icon"
          style={{ background: ICONS[l.label].color }}
          aria-label={`Написати у ${l.label}`}
          title={l.label}
        >
          <svg viewBox="0 0 24 24" width="26" height="26" fill="#fff" aria-hidden="true">
            <path d={ICONS[l.label].path} />
          </svg>
        </a>
      ))}
    </div>
  );
}
